import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => { await page.goto(''); await expect(page.getByRole('heading', { name: 'Tudo conectado. Projetos em movimento.' })).toBeVisible() })

test('dashboard uses leaves, exposes demo context and navigates from cards', async ({ page }) => {
  await expect(page.getByText('Demonstração interativa', { exact: true })).toBeVisible()
  const card = page.locator('.project-card').filter({ hasText: 'Padronização de processos' })
  await expect(card).toContainText('75,0%')
  await expect(card).toContainText('3/4')
  await card.getByRole('button', { name: 'Padronização de processos' }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Padronização de processos' })).toBeVisible()
  await expect(page.getByText('Progresso: 3 de 4 folhas concluídas')).toBeVisible()
})

test('project completion is blocked until parent and children are done; history persists', async ({ page }) => {
  await page.getByRole('button', { name: 'Padronização de processos' }).click()
  await page.getByRole('button', { name: 'Concluir projeto', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('todas as tarefas e subtarefas concluídas')
  await page.getByLabel('Status de Construir guia de procedimentos', { exact: true }).selectOption('done')
  await expect(page.getByRole('status')).toContainText('Conclua todas as subtarefas')
  await expect(page.getByLabel('Status de Construir guia de procedimentos', { exact: true })).toHaveValue('in_progress')
  await page.getByLabel('Status de Revisar versão final do guia', { exact: true }).selectOption('done')
  await page.getByLabel('Status de Construir guia de procedimentos', { exact: true }).selectOption('done')
  await page.getByRole('button', { name: 'Concluir projeto', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Reabrir projeto' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Reabrir projeto' })).toBeVisible()
  await page.getByRole('link', { name: 'Histórico', exact: true }).click()
  await expect(page.getByText('Projeto concluído', { exact: true })).toBeVisible()
})

test('creates a synthetic project, task and subtask with eligible assignees', async ({ page }) => {
  await page.getByRole('button', { name: 'Novo projeto', exact: true }).click()
  await page.getByLabel('Nome do projeto').fill('Projeto E2E fictício')
  await page.getByLabel('Ana Demo', { exact: true }).check()
  await page.getByRole('button', { name: 'Salvar na demonstração' }).click()
  await expect(page.getByRole('heading', { name: 'Projeto E2E fictício', exact: true })).toBeVisible()
  await expect(page.getByText('Progresso: 0 de 0 folhas concluídas')).toBeVisible()
  await page.getByRole('button', { name: 'Nova tarefa', exact: true }).click()
  await page.getByLabel('Título', { exact: true }).fill('Entrega E2E fictícia')
  await page.getByLabel('Responsável', { exact: true }).selectOption({ label: 'Ana Demo' })
  await page.getByRole('button', { name: 'Salvar na demonstração' }).click()
  await expect(page.getByText('Entrega E2E fictícia', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Nova tarefa', exact: true }).click()
  await page.getByLabel('Título', { exact: true }).fill('Subentrega E2E fictícia')
  await page.getByLabel('Tipo', { exact: true }).selectOption({ label: 'Subtarefa de: Entrega E2E fictícia' })
  await page.getByLabel('Responsável', { exact: true }).selectOption({ label: 'Ana Demo' })
  await page.getByRole('button', { name: 'Salvar na demonstração' }).click()
  await expect(page.getByText('Progresso: 0 de 1 folhas concluídas')).toBeVisible()
  await expect(page.getByText('Subentrega E2E fictícia', { exact: true })).toBeVisible()
})

test('task search does not filter by project title and Kanban supports keyboard-friendly changes', async ({ page }) => {
  await page.getByRole('link', { name: 'Tarefas', exact: true }).click()
  await page.getByLabel('Buscar', { exact: true }).fill('catálogo')
  await expect(page.getByText('Validar catálogo de serviços', { exact: true })).toBeVisible()
  await expect(page.getByText('Mapear processos atuais', { exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Kanban', exact: true }).click()
  await page.getByLabel('Mover Validar catálogo de serviços', { exact: true }).selectOption('done')
  await expect(page.locator('.kanban-column.done')).toContainText('Validar catálogo de serviços')
})

test('role simulation has no real login; executive is read-only and admin can add demo departments', async ({ page }) => {
  await page.getByLabel('Visão demonstrativa').selectOption('executive')
  await expect(page.getByRole('button', { name: 'Novo projeto', exact: true })).toHaveCount(0)
  await page.getByLabel('Visão demonstrativa').selectOption('administrator')
  await page.getByRole('link', { name: 'Pessoas e departamentos', exact: true }).click()
  await page.getByRole('button', { name: 'Novo departamento', exact: true }).click()
  await page.getByLabel('Nome fictício do departamento').fill('Departamento E2E fictício')
  await page.getByRole('button', { name: 'Salvar na demonstração' }).click()
  await expect(page.getByRole('heading', { name: 'Departamento E2E fictício', exact: true })).toBeVisible()
  await expect(page.locator('input[type="password"]')).toHaveCount(0)
})

test('360px navigation and dialog operate without page overflow', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.getByRole('button', { name: 'Abrir menu' }).click()
  await page.getByRole('navigation', { name: 'Menu principal' }).getByRole('link', { name: /^Projetos/ }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Projetos', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Novo projeto', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
